import { generateImage } from '@bitbaum/ai-kit/images';
import { clientIp, slidingWindow, toHeaders } from 'limitkit';
import { randomBytes } from 'node:crypto';

import { BodyTooLarge, originAllowed, readBoundedJson } from '@/lib/api/guard';
import { db } from '@/lib/db/client';
import { generatedImages } from '@/lib/db/schema';
import { illustrationPrompt, imageGenConfig } from '@/lib/investigations/ai-image';
import {
  canEditInvestigation,
  getInvestigation,
  updateInvestigation,
} from '@/lib/investigations/store';
import { PUBLIC_ID } from '@/lib/reports/store';

export const runtime = 'nodejs';
export const dynamic = 'force-dynamic';
export const maxDuration = 120;

type Context = { params: Promise<{ id: string }> };
const perIp = slidingWindow({ limit: 6, windowMs: 24 * 60 * 60_000 });
const global = slidingWindow({ limit: 40, windowMs: 24 * 60 * 60_000 });
const fail = (message: string, status: number, headers?: HeadersInit) =>
  Response.json({ ok: false, error: { message } }, { status, headers });

/** GET: is AI illustration switched on here? */
export async function GET() {
  return Response.json({
    ok: true,
    enabled: imageGenConfig() !== null && !!process.env.DATABASE_URL,
  });
}

/** Body: { editToken, revision, subject }. Generates one labelled AI illustration and adds it. */
export async function POST(request: Request, { params }: Context) {
  const { id } = await params;
  if (!originAllowed(request)) return fail('Request origin is not allowed.', 403);
  if (!PUBLIC_ID.test(id)) return fail('Unknown investigation.', 404);
  const config = imageGenConfig();
  if (!config || !process.env.DATABASE_URL)
    return fail('AI illustrations are not switched on on this server.', 503);
  let body: Record<string, unknown>;
  try {
    body = (await readBoundedJson(request, 3_000)) as Record<string, unknown>;
  } catch (error) {
    return error instanceof BodyTooLarge
      ? fail('Request body is too large.', 413)
      : fail('Request body must be JSON.', 400);
  }
  const subject = typeof body?.subject === 'string' ? body.subject.trim() : '';
  if (
    typeof body?.editToken !== 'string' ||
    !Number.isInteger(body.revision) ||
    subject.length < 4 ||
    subject.length > 400
  )
    return fail('Send editToken, revision and what the illustration should show.', 400);
  if (!(await canEditInvestigation(db, id, body.editToken)))
    return fail('This link cannot edit that investigation.', 403);
  const saved = await getInvestigation(db, id);
  if (!saved) return fail('Unknown investigation.', 404);
  if (saved.revision !== body.revision)
    return fail('Someone saved a newer version. Reload first.', 409);
  if ((saved.investigation.images ?? []).length >= 6)
    return fail('This investigation already has six images.', 409);
  const limit = perIp.check('img:' + clientIp(request.headers));
  const headers = toHeaders(limit);
  if (!limit.allowed || !global.check('img:all').allowed)
    return fail('Illustration limit reached for today.', 429, headers);

  const result = await generateImage({
    ...config,
    prompt: illustrationPrompt(subject),
    signal: request.signal,
  });
  if (!result.ok)
    return fail(
      'The image service could not make this illustration: ' + result.error,
      502,
      headers,
    );
  const imageId = randomBytes(12).toString('base64url');
  await db.insert(generatedImages).values({
    id: imageId,
    investigationId: id,
    mimeType: result.image.mimeType,
    dataBase64: Buffer.from(result.image.bytes).toString('base64'),
    prompt: subject,
  });
  const next = {
    ...saved.investigation,
    images: [
      {
        kind: 'ai' as const,
        src: '/api/images/generated/' + imageId,
        alt: 'AI-generated illustration: ' + subject.slice(0, 160),
        caption: 'AI-generated illustration of: ' + subject.slice(0, 200),
        credit: 'Generated by AI for BiasLens',
        license: 'AI-generated · not a photograph',
        licenseUrl: null,
        sourceUrl: null,
      },
      ...(saved.investigation.images ?? []),
    ],
  };
  const outcome = await updateInvestigation(db, id, body.editToken, saved.revision, next);
  if (!outcome.ok)
    return fail('Could not save the illustration (' + outcome.reason + ').', 409, headers);
  return Response.json(
    { ok: true, revision: outcome.revision, src: '/api/images/generated/' + imageId },
    { headers },
  );
}
